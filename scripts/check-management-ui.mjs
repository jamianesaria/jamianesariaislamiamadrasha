import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE || undefined });
const errors = [];
mkdirSync(".cms-work/management-qa", { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const note = "Browser QA saved note " + Date.now();
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("http://127.0.0.1:3030", { waitUntil: "domcontentloaded", timeout: 60000 });
  await page.getByRole("heading", { name: /আসসালামু/ }).waitFor();
  await page.waitForFunction(() => !document.querySelector(".m-stats")?.textContent.includes("—"));
  assert.equal(await page.locator('[role="alert"]').count(), 0);
  await page.screenshot({ path: ".cms-work/management-qa/dashboard-desktop.png", fullPage: true });
  console.log("Dashboard shows real counts without errors");
  await page.locator(".m-sidebar").getByRole("button", { name: "যোগাযোগ বার্তা", exact: true }).click();
  await page.getByPlaceholder("নাম, মোবাইল বা আবেদন নম্বর…").fill("Browser QA");
  await page.getByRole("button", { name: "বিস্তারিত", exact: true }).first().click();
  const dialog = page.getByRole("dialog");
  await dialog.waitFor();
  await dialog.getByLabel("আবেদনের অগ্রগতি").selectOption("review");
  await dialog.getByLabel("অফিসের ব্যক্তিগত মন্তব্য").fill(note);
  await page.screenshot({ path: ".cms-work/management-qa/inbox-detail.png" });
  await dialog.getByRole("button", { name: "পরিবর্তন সংরক্ষণ করুন" }).click();
  await dialog.waitFor({ state: "detached" });
  await page.getByRole("button", { name: "বিস্তারিত", exact: true }).first().click();
  await page.getByRole("dialog").getByLabel("অফিসের ব্যক্তিগত মন্তব্য").waitFor();
  assert.equal(await page.getByRole("dialog").getByLabel("অফিসের ব্যক্তিগত মন্তব্য").inputValue(), note);
  await page.setViewportSize({ width: 390, height: 844 });
  await dialog.getByRole("button", { name: "মুছে ফেলুন", exact: true }).click();
  const confirmation = page.getByRole("alertdialog");
  await confirmation.waitFor();
  const confirm = confirmation.getByRole("button", { name: "স্থায়ীভাবে মুছুন", exact: true });
  assert.equal(await confirm.isDisabled(), true);
  const rect = await confirmation.boundingBox();
  assert.ok(rect.x >= 0 && rect.x + rect.width <= 391);
  await confirmation.getByRole("button", { name: "ফিরে যান" }).click();
  await confirmation.waitFor({ state: "detached" });
  assert.equal(await dialog.count(), 1, "Cancelling deletion must preserve the detail panel");
  await dialog.getByRole("button", { name: "মুছে ফেলুন", exact: true }).click();
  await confirmation.getByRole("checkbox").check();
  await page.screenshot({ path: ".cms-work/management-qa/delete-phone.png" });
  await confirm.click();
  await dialog.waitFor({ state: "detached" });
  await page.locator(".m-table tbody tr").waitFor({ state: "detached" });
  await page.setViewportSize({ width: 1440, height: 1000 });
  console.log("Inbox detail, persisted notes, workflow status, and reopening passed");
  await page.locator(".m-sidebar").getByRole("button", { name: "নোটিশ ও ঘোষণা", exact: true }).click();
  await page.locator(".m-table tbody tr").first().waitFor();
  assert.match(await page.getByRole("link", { name: "নতুন যোগ করুন" }).getAttribute("href"), /type=notice/);
  await page.screenshot({ path: ".cms-work/management-qa/notices.png" });
  await page.getByPlaceholder("শিরোনাম দিয়ে খুঁজুন…").fill("Delete browser QA publication");
  const ownRow = page.locator(".m-table tbody tr").filter({ hasText: "Delete browser QA publication" });
  await ownRow.waitFor();
  await ownRow.getByRole("button", { name: "মুছে ফেলুন", exact: true }).click();
  await confirmation.getByRole("checkbox").check();
  await confirm.click();
  await ownRow.waitFor({ state: "detached" });
  await page.getByRole("status").filter({ hasText: "স্থায়ীভাবে মুছে" }).waitFor();
  console.log("Confirmed public and private deletion, cancellation, disabled unchecked confirmation and phone dialog passed");
  await page.locator(".m-sidebar").getByRole("button", { name: /ওয়েবসাইট সম্পাদনা/ }).click();
  assert.equal(await page.evaluate(() => window.__managementNavigation?.tool), "presentation");
  console.log("Publication listing, create intent and visual-editor navigation passed");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "মেনু খুলুন" }).click();
  await page.locator(".m-sidebar").getByRole("button", { name: "ড্যাশবোর্ড", exact: true }).click();
  await page.getByRole("heading", { name: /আসসালামু/ }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.waitForFunction(() => !document.querySelector(".m-stats")?.textContent.includes("—"));
  await page.waitForFunction(() => document.querySelector(".m-sidebar").getBoundingClientRect().right <= 1);
  await page.screenshot({ path: ".cms-work/management-qa/dashboard-phone.png" });
  await page.emulateMedia({ reducedMotion: "reduce" });
  assert.ok(await page.locator(".m-sidebar").evaluate(element => element.getBoundingClientRect().right <= 1), "Reduced motion must keep the closed mobile menu off screen");
  assert.deepEqual(errors, []);
  console.log("Phone layout, navigation, and zero browser runtime errors verified");
  await page.request.get("http://127.0.0.1:3030/qa/cleanup");
  console.log("Temporary private browser QA record removed");
} finally { await browser.close(); }
